// ── Khôi phục các từ điển ngôn ngữ mới đã được AI tự sinh từ LocalStorage ─────
(function() {
    try {
        for (var i = 0; i < localStorage.length; i++) {
            var k = localStorage.key(i);
            if (k && k.indexOf('pastie_dict_') === 0) {
                var langCode = k.replace('pastie_dict_', '');
                var cached = JSON.parse(localStorage.getItem(k));
                if (cached && typeof cached === 'object') {
                    window.TRANSLATIONS[langCode] = Object.assign({}, window.TRANSLATIONS[langCode] || {}, cached);
                }
            }
        }
    } catch (e) {
        console.warn('[i18n] Lỗi đọc cache từ điển:', e);
    }
})();

// ── Helper dịch tĩnh dùng chung toàn cục ───────────────────────────────────────
window.t = function(key, fallback) {
    var lang = (typeof currentLang !== 'undefined' && currentLang) || localStorage.getItem('pastie_admin_lang') || 'vi';
    var dict = (window.TRANSLATIONS && window.TRANSLATIONS[lang]) || (window.TRANSLATIONS && window.TRANSLATIONS.vi) || {};
    if (dict && dict[key] !== undefined) return dict[key];
    return fallback !== undefined ? fallback : key;
};

// ── CƠ CHẾ TỰ ĐỘNG DỊCH AI CHO NGÔN NGỮ MỚI (SELF-EXPANDING AI TRANSLATOR) ────
// Nếu Superadmin thêm 1 mã ngôn ngữ mới chưa có trong từ điển (hoặc thiếu key),
// hàm này sẽ tự động gọi backend Gemini AI (batch) để dịch toàn bộ từ điển gốc
// sang ngôn ngữ mới đó, lưu vào cache và áp dụng mà không cần viết lại code.
window.ensureLanguageTranslations = async function(targetLang) {
    if (!targetLang || targetLang === 'vi') return true;
    targetLang = String(targetLang).trim().toLowerCase();

    if (!window.TRANSLATIONS) window.TRANSLATIONS = {};
    if (!window.TRANSLATIONS[targetLang]) window.TRANSLATIONS[targetLang] = {};

    var baseDict = window.TRANSLATIONS.vi || {};
    var targetDict = window.TRANSLATIONS[targetLang] || {};

    // Tìm các key còn thiếu
    var allKeys = Object.keys(baseDict);
    var missingKeys = allKeys.filter(function(k) {
        return !targetDict[k] || targetDict[k] === baseDict[k];
    });

    if (missingKeys.length === 0) {
        return true;
    }

    console.log('[i18n AI] Phát hiện ngôn ngữ mới/thiếu từ khóa: ' + targetLang + ' (' + missingKeys.length + ' keys). Đang tự động gọi Gemini AI dịch...');

    if (typeof showToast === 'function') {
        showToast('Đang dùng AI tạo bản dịch cho ngôn ngữ ' + targetLang.toUpperCase() + '...', 'info');
    }

    var textsToTranslate = missingKeys.map(function(k) { return baseDict[k]; });
    var apiBase = (typeof API_BASE !== 'undefined' && API_BASE) || window.PASTIE_API_BASE || '';

    try {
        var res = await fetch(apiBase + '/api/ai/translate-batch', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                texts: textsToTranslate,
                targetLang: targetLang,
                sourceLang: 'vi'
            })
        });

        if (!res.ok) throw new Error('HTTP ' + res.status);
        var data = await res.json();

        if (data && Array.isArray(data.translations)) {
            data.translations.forEach(function(translated, idx) {
                var k = missingKeys[idx];
                targetDict[k] = translated || baseDict[k];
            });
            window.TRANSLATIONS[targetLang] = targetDict;

            // Lưu vào localStorage để các lần sau nạp tức thì 0ms
            try {
                localStorage.setItem('pastie_dict_' + targetLang, JSON.stringify(targetDict));
            } catch (e) {}

            console.log('[i18n AI] Đã tự động dịch và nạp thành công ngôn ngữ ' + targetLang + '!');
            if (typeof showToast === 'function') {
                showToast('Đã hoàn tất tự động dịch sang ' + targetLang.toUpperCase() + '!', 'success');
            }
            return true;
        }
    } catch (err) {
        console.error('[i18n AI] Lỗi tự động dịch ngôn ngữ mới:', err);
    }
    return false;
};

// ── Tự động dịch một chuỗi động (Dynamic String) bằng AI ───────────────────────
window.tDynamic = async function(text, targetLang) {
    if (!text) return '';
    targetLang = targetLang || (typeof currentLang !== 'undefined' && currentLang) || 'vi';
    if (targetLang === 'vi') return text;

    var cacheKey = 'dyn:' + targetLang + ':' + text;
    var cached = sessionStorage.getItem(cacheKey);
    if (cached) return cached;

    try {
        var apiBase = (typeof API_BASE !== 'undefined' && API_BASE) || window.PASTIE_API_BASE || '';
        var res = await fetch(apiBase + '/api/ai/translate-batch', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ texts: [text], targetLang: targetLang, sourceLang: 'vi' })
        });
        var data = await res.json();
        if (data && data.translations && data.translations[0]) {
            sessionStorage.setItem(cacheKey, data.translations[0]);
            return data.translations[0];
        }
    } catch (e) {}
    return text;
};
